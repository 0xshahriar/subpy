"""File writers for every supported output format.

One entry point — :func:`write_output` — plus a small class per format. Each
writer is streaming-friendly (it takes an iterable of hosts) and produces
output that is *useful as-is*: the JSON is machine-parseable, the CSV opens
in a spreadsheet, the Markdown tables render on GitHub, and the HTML is a
single self-contained file that looks right on a phone.

Hostnames are untrusted input. Every writer escapes what it emits, and the
HTML writer emits no script at all — a discovered subdomain containing
``<script>`` must not become stored XSS in your report.
"""

from __future__ import annotations

import csv
import html
import io
import json
import os
import time
from collections.abc import Iterable, Sequence
from typing import TextIO

from ..core.models import Host, ScanSummary

__all__ = ["write_output", "FORMATS", "format_hosts"]

FORMATS: Sequence[str] = ("txt", "json", "csv", "md", "html")


def _sorted(hosts: Iterable[Host]) -> list[Host]:
    return sorted(hosts, key=lambda h: (h.name.count("."), h.name))


# --------------------------------------------------------------------------
# Plain text: one host per line. Pipe-friendly, the default.
# --------------------------------------------------------------------------
def _write_txt(hosts: list[Host], stream: TextIO, *, with_ip: bool = False) -> None:
    for host in _sorted(hosts):
        if with_ip and host.ip:
            stream.write(f"{host.name}\t{host.ip}\n")
        else:
            stream.write(host.name + "\n")


# --------------------------------------------------------------------------
# JSON: a stable schema with a metadata block, so consumers can rely on it.
# --------------------------------------------------------------------------
def _write_json(hosts: list[Host], stream: TextIO, summary: ScanSummary | None) -> None:
    payload = {
        "tool": "subpy",
        "schema": 1,
        "generated_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "count": len(hosts),
        "summary": summary.to_dict() if summary is not None else {},
        "hosts": [h.to_dict() for h in _sorted(hosts)],
    }
    json.dump(payload, stream, indent=2, ensure_ascii=False)
    stream.write("\n")


# --------------------------------------------------------------------------
# CSV: fixed header order so downstream scripts never break.
# --------------------------------------------------------------------------
CSV_COLUMNS = ("host", "ip", "ipv6", "cname", "status", "server", "title", "sources", "ttl")


def _write_csv(hosts: list[Host], stream: TextIO) -> None:
    writer = csv.writer(stream, lineterminator="\n")
    writer.writerow(CSV_COLUMNS)
    for host in _sorted(hosts):
        writer.writerow(
            [
                host.name,
                ";".join(host.addresses),
                ";".join(host.addresses_v6),
                ";".join(host.cnames),
                "" if host.http_status is None else host.http_status,
                host.server,
                host.http_title,
                ";".join(sorted(host.sources)),
                host.ttl or "",
            ]
        )


# --------------------------------------------------------------------------
# Markdown: GitHub-flavoured, narrow enough to read on a phone.
# --------------------------------------------------------------------------
def _md_escape(value: str) -> str:
    return str(value).replace("|", "\\|").replace("\n", " ").strip()


def _write_md(hosts: list[Host], stream: TextIO, summary: ScanSummary | None) -> None:
    ordered = _sorted(hosts)
    domain = summary.domain if summary is not None else ""

    stream.write(f"# Subdomains{' for ' + domain if domain else ''}\n\n")
    if summary is not None:
        stream.write(
            f"**{len(ordered)}** hosts &middot; "
            f"{summary.elapsed:.1f}s &middot; "
            f"{summary.queries} queries\n\n"
        )

    stream.write("| Host | IP | Sources |\n")
    stream.write("| --- | --- | --- |\n")
    for host in ordered:
        address = host.ip or ("cname:" + host.cnames[0] if host.cnames else "-")
        sources = ", ".join(sorted(host.sources)[:3]) or "-"
        stream.write(
            f"| `{_md_escape(host.name)}` | {_md_escape(address)} | {_md_escape(sources)} |\n"
        )

    stream.write("\n---\n\n")
    stream.write("*Generated by [subpy](https://github.com/0xShahriar/subpy).*\n")


