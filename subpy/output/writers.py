def _write_html(hosts: list[Host], stream: TextIO, summary: ScanSummary | None) -> None:
    ordered = _sorted(hosts)
    domain = summary.domain if summary is not None else "subdomains"
    title = html.escape(f"Subdomains for {domain}" if domain else "Subdomains")

    rows = []
    for host in ordered:
        address = host.ip or (f"cname {host.cnames[0]}" if host.cnames else "&ndash;")
        chips = "".join(
            f'<span class="chip">{html.escape(s)}</span>' for s in sorted(host.sources)[:4]
        )
        rows.append(
            "<tr>"
            f'<td class="host">{html.escape(host.name)}</td>'
            f'<td class="ip col-ip">{html.escape(address)}</td>'
            f'<td class="col-src">{chips or "&ndash;"}</td>'
            "</tr>"
        )

    stream.write(
        _HTML_TEMPLATE.format(
            title=title,
            count=len(ordered),
            elapsed=f"{summary.elapsed:.1f}s" if summary is not None else "",
            when=time.strftime("%Y-%m-%d %H:%M UTC", time.gmtime()),
            rows="\n".join(rows),
        )
    )


# --------------------------------------------------------------------------
# Dispatch
# --------------------------------------------------------------------------
def format_hosts(
    hosts: Iterable[Host],
    fmt: str,
    *,
    summary: ScanSummary | None = None,
    with_ip: bool = False,
) -> str:
    """Render hosts to a string in the requested format."""
    fmt = (fmt or "txt").lower()
    if fmt not in FORMATS:
        raise ValueError(f"unknown format {fmt!r}; choose from {', '.join(FORMATS)}")
    buffer = io.StringIO()
    ordered = list(hosts)
    if fmt == "txt":
        _write_txt(ordered, buffer, with_ip=with_ip)
    elif fmt == "json":
        _write_json(ordered, buffer, summary)
    elif fmt == "csv":
        _write_csv(ordered, buffer)
    elif fmt == "md":
        _write_md(ordered, buffer, summary)
    elif fmt == "html":
        _write_html(ordered, buffer, summary)
    return buffer.getvalue()


def write_output(
    hosts: Iterable[Host],
    path: str,
    fmt: str = "txt",
    *,
    summary: ScanSummary | None = None,
    with_ip: bool = False,
) -> str:
    """Write hosts to *path*. Returns the path actually written.

    The extension is honoured when *fmt* is not given explicitly, and the
    parent directory is created so ``-o results/x.json`` just works.
    """
    content = format_hosts(hosts, fmt, summary=summary, with_ip=with_ip)
    directory = os.path.dirname(os.path.abspath(path))
    if directory and not os.path.isdir(directory):
        os.makedirs(directory, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="") as handle:
        handle.write(content)
    return path
