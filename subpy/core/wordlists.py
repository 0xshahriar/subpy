def _split_label(label: str) -> list[str]:
    return [p for p in re.split(r"[-_.]", label) if p]


def generate_permutations(
    known_labels: Iterable[str],
    *,
    domain: str = "",
    max_per_label: int = 60,
    extra_words: Sequence[str] | None = None,
) -> Iterator[str]:
    """Generate plausible sibling labels from known ones.

    Strategy (highest yield first):
      * ``label`` + number / short suffix          -> ``api2``, ``api-prod``
      * prefix + ``label``                         -> ``dev-api``
      * prefix + number + ``label`` / ``label`` + number + suffix
      * environment swaps on multi-part labels     -> ``dev-api`` -> ``dev-db``
      * word-level substitution from the built-in list
      * hyphen/underscore/dot variants

    Every output is a bare label; duplicates are suppressed globally.
    """
    seen: set[str] = set()
    vocab = list(extra_words or ()) + [w for w in BUILTIN_WORDLIST if len(w) > 2][:400]

    def emit(candidate: str) -> Iterator[str]:
        candidate = candidate.strip("-._").lower()
        if not candidate or len(candidate) > 63:
            return
        if not re.fullmatch(r"[a-z0-9_](?:[a-z0-9_\-]*[a-z0-9_])?", candidate):
            return
        if candidate in seen:
            return
        seen.add(candidate)
        yield candidate

    for raw_label in known_labels:
        label = raw_label.split(".", 1)[0].lower()
        if not label or label == "www":
            # "www" permutations are pure noise; it is always enumerated.
            continue
        produced = 0

        # 1. numeric and short suffixes
        for num in _NUMBERS:
            if produced >= max_per_label:
                break
            for sep in ("", "-", "."):
                for out in emit(f"{label}{sep}{num}"):
                    produced += 1
                    yield out

        # 2. environment prefixes/suffixes
        for word in _PREFIXES + _SUFFIXES:
            if produced >= max_per_label:
                break
            for candidate in (
                f"{label}-{word}",
                f"{label}{word}",
                f"{word}-{label}",
                f"{word}{label}",
            ):
                for out in emit(candidate):
                    produced += 1
                    yield out

        # 3. word substitution inside multi-part labels
        parts = _split_label(label)
        if len(parts) >= 2:
            for index in range(len(parts)):
                for word in (_PREFIXES + _SUFFIXES)[:20]:
                    if produced >= max_per_label:
                        break
                    if word == parts[index]:
                        continue
                    variant = list(parts)
                    variant[index] = word
                    for out in emit("-".join(variant)):
                        produced += 1
                        yield out

        # 4. separator variants
        for sep in ("-", "_", "."):
            for out in emit(sep.join(parts)):
                produced += 1
                yield out

        # 5. vocabulary composition (bounded, most useful words only)
        for word in vocab:
            if produced >= max_per_label:
                break
            for candidate in (f"{label}-{word}", f"{word}-{label}", f"{label}{word}"):
                for out in emit(candidate):
                    produced += 1
                    yield out
