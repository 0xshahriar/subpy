_COMMENT_RE = re.compile(r"(^|\s)#")


def _iter_file(path: str) -> Iterator[str]:
    with open(path, encoding="utf-8", errors="ignore") as handle:
        for line in handle:
            line = line.strip()
            if not line:
                continue
            if line.startswith("#") or line.startswith("//"):
                continue
            yield line


def iter_wordlist(
    *,
    domain: str = "",
    paths: Sequence[str] | None = None,
    builtin: bool = True,
    limit: int = 0,
    extra: Sequence[str] | None = None,
) -> Iterator[str]:
    """Yield unique, semantically valid labels for brute forcing.

    Accepts bare labels (``dev``), full hostnames (``dev.example.com``) and
    hosts with wildcards, normalising each to a single label relative to
    *domain*. Streaming keeps memory flat for million-line lists.
    """
    seen: set[str] = set()
    emitted = 0
    domain = (domain or "").lower().rstrip(".")
    suffix = "." + domain if domain else ""

    def _clean(raw: str) -> str | None:
        raw = raw.strip().strip("*.").strip()
        if not raw:
            return None
        # Whole-host entries: keep only the label part below the target.
        if suffix and raw.lower().endswith(suffix):
            raw = raw[: -len(suffix)]
        elif domain and raw.lower() == domain:
            return None
        raw = raw.strip(".")
        # Without a domain to anchor against, only bare labels are usable.
        if "." in raw:
            return None
        if not re.fullmatch(r"[a-z0-9_](?:[a-z0-9_\-]{0,61}[a-z0-9_])?", raw.lower()):
            return None
        return raw.lower()

    def _push(raw: str) -> Iterator[str]:
        nonlocal emitted
        label = _clean(raw)
        if label is None or label in seen:
            return
        seen.add(label)
        emitted += 1
        yield label

    for source in extra or []:
        yield from _push(source)

    for path in paths or []:
        try:
            for line in _iter_file(path):
                if limit and emitted >= limit:
                    return
                yield from _push(line)
        except OSError:
            continue

    if builtin and not limit:
        for label in load_builtin_file():
            if label not in seen:
                seen.add(label)
                yield label
    elif builtin:
        for label in load_builtin_file():
            if emitted >= limit:
                return
            if label not in seen:
                seen.add(label)
                emitted += 1
                yield label
    elif limit:
        return


def load_wordlist(path: str, domain: str = "") -> list[str]:
    """Read a whole wordlist into memory (used by permutation seeding)."""
    return list(iter_wordlist(paths=[path], builtin=False, domain=domain))


def load_builtin_file() -> list[str]:
    """Read ``subpy/data/builtin.txt`` when it ships with the install.

    The list is also embedded in this module, so a stripped install (a bare
    ``.py`` copied onto a device, a zipapp without data) still works. The file
    wins when present because users can edit it in place.
    """
    path = os.path.join(WORDLIST_DIR, "builtin.txt")
    try:
        with open(path, encoding="utf-8", errors="ignore") as handle:
            labels = [
                line.strip().lower()
                for line in handle
                if line.strip() and not line.lstrip().startswith("#")
            ]
    except OSError:
        return list(BUILTIN_WORDLIST)
    return labels or list(BUILTIN_WORDLIST)


def resolve_wordlist_path(name: str) -> str | None:
    """Resolve a built-in wordlist name or an existing path."""
    candidates = [
        name,
        os.path.join(WORDLIST_DIR, name),
        os.path.join(WORDLIST_DIR, f"{name}.txt"),
    ]
    for candidate in candidates:
        if os.path.isfile(candidate):
            return candidate
    return None


