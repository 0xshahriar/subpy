"""Wordlist handling and permutation generation.

A subdomain finder is only as good as the names it guesses. Three things
matter:

1. **A good default list.** Shipping a curated ~1200-entry list tuned for
   real-world hit rates beats making the user download SecLists on first run.
   It is embedded so ``pip install subpy`` is immediately useful offline.
2. **Permutations.** Once a single host is known (``dev-api.example.com``),
   generating siblings (``dev-api2``, ``dev-api-staging``, ``api-dev``) finds
   far more than blind brute force per query spent.
3. **Streaming, deduplicated, normalised input.** Wordlists from disk may be
   huge, contain comments, wildcards, full domains or duplicates.

The embedded list is intentionally ordered by observed effectiveness so that
``--limit`` truncation keeps the highest-value entries.
"""

